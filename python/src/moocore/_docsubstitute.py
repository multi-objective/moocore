from typing import Any, TypeVar
from collections.abc import Callable

from string import Template
import inspect

_CallableT = TypeVar("_CallableT", bound=Callable[..., Any])

COMMON_PARAMS = {
    "points": """2D array of numerical values, where each row gives the coordinates of a point in objective space.
    If the array is created by the :func:`read_datasets()` function, remove the last column.""",
    # -------------------------------------------------------------------------
    "maximise": """Whether the objectives must be maximised instead of minimised.
    Either a single boolean value that applies to all objectives or a list of boolean values, with one value per objective.
    Also accepts a 1D array with values 0 or 1 for each objective.""",
    # -------------------------------------------------------------------------
    "ref_set": """Reference set as a 2D array of numerical values. Must have the same number of columns as ``points``.""",
    # -------------------------------------------------------------------------
    "ref_point": """Reference point as a 1D vector. Must be either a single value, which will be used for all coordinates,
    or the same length as a single point in ``points``.""",
    # -------------------------------------------------------------------------
    "random_seed": """Either an integer to seed :func:`numpy.random.default_rng`, a Numpy
    default random number generator (RNG) or an instance of a Numpy-compatible RNG.
    ``None`` uses the equivalent of a random seed, as in :func:`numpy.random.default_rng`.""",
    # -------------------------------------------------------------------------
    "sets_of_points": """1D vector or list of values that gives the set of each row of ``points``.""",
    # -------------------------------------------------------------------------
    "whv_rectangles": """Weighted rectangles that will bias the computation of the hypervolume.
    Maybe generated by :func:`eafdiff()` with  ``rectangles=True`` or by :func:`choose_eafdiff()`.""",
    # -------------------------------------------------------------------------
    "parents": """2D array of numerical values, where each row is a decision vector.
    Rows ``2i`` and ``2i + 1`` are mated.  If the number of rows is odd, the last row is mated with the first one.""",
    # -------------------------------------------------------------------------
    "pair_offspring": """Array with the same shape as ``parents``, where rows ``2i`` and ``2i + 1`` are the two children of rows ``2i`` and ``2i + 1`` of ``parents``.
    If the number of rows is odd, the second child of the last pair is dropped, so the number of rows does not change.""",
    # -------------------------------------------------------------------------
    "population": """2D array of numerical values, where each row is a decision vector.""",
    # -------------------------------------------------------------------------
    "targets": """1D vector of row indices of ``population``.  Each index produces one child.  ``None`` uses every row.""",
    # -------------------------------------------------------------------------
    "lower_bound": """Lower bounds of the decision variables.  Either a single value, which will be used for all variables,
    or one value per column.  ``None`` means no lower bound.""",
    # -------------------------------------------------------------------------
    "upper_bound": """Upper bounds of the decision variables.  Either a single value, which will be used for all variables,
    or one value per column.  ``None`` means no upper bound.""",
}


class DocSubstitute:
    def __init__(self) -> None:
        self.params = COMMON_PARAMS

    def __call__(self, func: _CallableT) -> _CallableT:
        if func.__doc__:
            try:
                func.__doc__ = Template(
                    inspect.cleandoc(func.__doc__)
                ).substitute(self.params)
            except KeyError as e:
                missing = e.args[0]
                # Functors don't have __name__
                name = getattr(func, "__name__", "__call__")
                raise RuntimeError(
                    f"Missing docstring substitution for '{missing}' in {name}"
                )
        return func
